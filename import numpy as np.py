import numpy as np

# Create a simple array
arr = np.array([1, 2, 3, 4, 5])
print("Array:", arr)

# Create arrays filled with zeros and ones
zeros = np.zeros((2, 3))
ones = np.ones((3, 2))

print("\nZeros:\n", zeros)
print("\nOnes:\n", ones)

# Create a range of numbers
r = np.arange(0, 20, 2)   # Start, Stop, Step
print("\nRange array:", r)

